OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "presentation", "FontData.hpp")

lines = [
    "// Generated by tools/content_gen/gen_font.py - do not edit by hand.",
    "// Original 5x7 bitmap font. Lowercase maps to the uppercase glyph, giving",
    "// the UI a small-caps look with no external font dependency.",
    "#pragma once",
    "",
    "#include \"core/Types.hpp\"",
    "",
    "namespace df {",
    "",
    "inline constexpr int kGlyphWidth = 5;",
    "inline constexpr int kGlyphHeight = 7;",
    "inline constexpr int kGlyphFirst = 32;",
    "inline constexpr int kGlyphCount = 95;",
    "",
    "/// One byte per row; bit 4 is the leftmost pixel.",
    "inline constexpr u8 kFontRows[kGlyphCount][kGlyphHeight] = {",
]
for code in range(32, 127):
    ch = chr(code)
    key = ch.upper() if ch.upper() in G else ch
    rows = G.get(key, G.get(ch, G[' ']))
    vals = []
    for r in rows:
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= (1 << (4 - i))
        vals.append(f"0x{v:02X}")
    label = ch if ch not in ('\\',) else '\\\\'
    lines.append(f"    {{{', '.join(vals)}}}, // '{label}'")
lines.append("};")
lines.append("")
lines.append("} // namespace df")
with open(os.path.abspath(OUT), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", os.path.abspath(OUT))
