"""Emits src/presentation/FontData.hpp: an original 5x7 bitmap font.

Authored here as ASCII art so the glyphs stay editable. Lowercase letters map to
the same shapes as uppercase (a small-caps UI style), which keeps the font small
while remaining readable at 1080p through 4K.
"""
import os

